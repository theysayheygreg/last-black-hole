/**
 * text-corruption.js — Bounded Inhibitor text corruption.
 *
 * The Inhibitor is allowed to damage language, but not the DOM. Always strip
 * old combining marks before applying a new pass so animation never compounds
 * into unbounded strings.
 */

const COMBINING_MARK_RE = /[\u0300-\u036f\u1ab0-\u1aff\u1dc0-\u1dff\u20d0-\u20ff\ufe20-\ufe2f]/g;
const COMBINING_MARK_TEST_RE = /[\u0300-\u036f\u1ab0-\u1aff\u1dc0-\u1dff\u20d0-\u20ff\ufe20-\ufe2f]/;

const ABOVE_MARKS = [
  0x0301, 0x0302, 0x0303, 0x0307, 0x0308, 0x030a, 0x030b, 0x030c, 0x0311, 0x031b,
].map(codePointToMark);
const MIDDLE_MARKS = [
  0x0334, 0x0335, 0x0336, 0x0337, 0x0338,
].map(codePointToMark);
const BELOW_MARKS = [
  0x0316, 0x0317, 0x0318, 0x0319, 0x031c, 0x0323, 0x0324, 0x0325, 0x0326, 0x0329,
].map(codePointToMark);

function codePointToMark(codePoint) {
  return String.fromCharCode(codePoint);
}

function clamp(value, min, max) {
  return Math.max(min, Math.min(max, value));
}

function hashString(value) {
  let hash = 2166136261;
  const input = String(value ?? '');
  for (let i = 0; i < input.length; i++) {
    hash ^= input.charCodeAt(i);
    hash = Math.imul(hash, 16777619);
  }
  return hash >>> 0;
}

function mulberry32(seed) {
  let t = seed >>> 0;
  return () => {
    t += 0x6d2b79f5;
    let x = t;
    x = Math.imul(x ^ (x >>> 15), x | 1);
    x ^= x + Math.imul(x ^ (x >>> 7), x | 61);
    return ((x ^ (x >>> 14)) >>> 0) / 4294967296;
  };
}

function isCorruptibleChar(char, preserveDigits) {
  if (!char || /\s/.test(char)) return false;
  if (preserveDigits && /[0-9]/.test(char)) return false;
  return !COMBINING_MARK_TEST_RE.test(char);
}

function pickMarkPool(amount, roll) {
  if (amount < 0.28) return ABOVE_MARKS;
  if (amount < 0.58) return roll < 0.7 ? ABOVE_MARKS : MIDDLE_MARKS;
  if (roll < 0.45) return ABOVE_MARKS;
  if (roll < 0.7) return MIDDLE_MARKS;
  return BELOW_MARKS;
}

/**
 * Remove combining marks from text, including marks generated by this module.
 */
export function stripCombiningMarks(text) {
  return String(text ?? '').normalize('NFD').replace(COMBINING_MARK_RE, '').normalize('NFC');
}

/**
 * Apply deterministic, capped combining-mark corruption.
 *
 * @param {string} text plain source text
 * @param {number} intensity 0..1 corruption amount
 * @param {string|number} seed stable seed for deterministic output
 * @param {object} options density/maxMarks/preserveDigits/maxChars
 * @returns {string}
 */
export function corruptText(text, intensity = 0, seed = 0, options = {}) {
  const clean = stripCombiningMarks(text);
  const amount = clamp(Number(intensity) || 0, 0, 1);
  const maxMarks = clamp(Math.round(Number(options.maxMarks ?? 3) || 0), 0, 8);
  if (amount <= 0.02 || maxMarks <= 0) return clean;

  const maxChars = clamp(Math.round(Number(options.maxChars ?? 160) || 160), 1, 512);
  const density = clamp(Number(options.density ?? 0.75) || 0, 0, 1);
  const preserveDigits = options.preserveDigits !== false;
  const chance = clamp(amount * density, 0, 1);
  const marksAtThisAmount = clamp(Math.ceil(maxMarks * (0.35 + amount * 0.65)), 1, maxMarks);
  const random = mulberry32(hashString(`${clean}|${seed}`));
  const out = [];
  let baseChars = 0;

  for (const char of clean) {
    if (baseChars >= maxChars) break;
    out.push(char);
    baseChars++;

    if (!isCorruptibleChar(char, preserveDigits) || random() > chance) continue;

    const markCount = 1 + Math.floor(random() * marksAtThisAmount);
    for (let i = 0; i < markCount; i++) {
      const pool = pickMarkPool(amount, random());
      out.push(pool[Math.floor(random() * pool.length)]);
    }
  }

  return out.join('');
}
