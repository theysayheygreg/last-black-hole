#!/usr/bin/env node

const fs = require('fs');
const path = require('path');
const { pathToFileURL } = require('url');

const ROOT = path.resolve(__dirname, '..');
const OUTPUT = path.join(ROOT, 'src', 'ui', 'design-tokens.css');

async function renderUiTokenCss() {
  const { UI_CSS_VARIABLES } = await import(pathToFileURL(path.join(ROOT, 'src', 'ui', 'design-tokens.js')).href);
  const lines = Object.entries(UI_CSS_VARIABLES).map(([name, value]) => `  --lbh-${name}: ${value};`);
  return `/* Generated by scripts/generate-ui-token-css.cjs. Do not edit. */\n:root {\n${lines.join('\n')}\n}\n`;
}

async function main() {
  const css = await renderUiTokenCss();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : '';
    if (current !== css) throw new Error('src/ui/design-tokens.css is stale; run node scripts/generate-ui-token-css.cjs');
    return;
  }
  fs.writeFileSync(OUTPUT, css);
}

if (require.main === module) main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});

module.exports = { renderUiTokenCss };
